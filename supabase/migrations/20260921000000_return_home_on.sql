-- ============================================================
-- 帰国予定時期
--
-- 対象となる人材の多くは「今は日本にいるが、いずれ母国に帰る」層で、
-- 企業側（アフリカ進出を検討する日本企業）にとっては、その人がいつ現地に
-- 戻るのかが最も重要な情報になる。
--
-- 登録時にしか聞けない情報のため先に受け皿を作る。「帰国が近い人を抽出して
-- 連絡する」用途で範囲検索するので、自由記述ではなくdateで持つ。
-- 日までは分からないのが普通なので、月初（YYYY-MM-01）で保存する運用とし、
-- 未定は null。
-- ============================================================

alter table public.profiles
  add column return_home_on date;

comment on column public.profiles.return_home_on is
  '帰国予定時期。月初で保存（YYYY-MM-01）。nullは未定。';
