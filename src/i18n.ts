export function t(lang: Lang, path: string): string {
  const result = path.split('.').reduce<unknown>((obj, key) => {
    if (obj && typeof obj === 'object') return (obj as Record<string, unknown>)[key]
    return undefined
  }, translations[lang])
  return typeof result === 'string' ? result : path
}
